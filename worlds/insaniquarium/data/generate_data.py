#!/usr/bin/env python3
"""
generate_data.py

Single Source of Truth generator for Insaniquarium Deluxe Archipelago integration.
Reads:
  - world/insaniquarium/data/items.json
  - world/insaniquarium/data/locations.json

Generates:
  - world/insaniquarium/APDefinitions.h              (C++ enums, constants, string converters)
  - world/insaniquarium/data/item_data.py            (Python APItem IntEnum, item_table, groups)
  - world/insaniquarium/data/location_data.py        (Python InsaniquariumLocationData, groups)

Usage:
  python generate_data.py
  python generate_data.py --check   (verifies files are in sync without writing)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List


IDENTIFIER_REGEX = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

CLASSIFICATION_MAP = {
    "progression": "IC.progression",
    "useful": "IC.useful",
    "filler": "IC.filler",
    "trap": "IC.trap",
    "progression_skip_balancing": "IC.progression_skip_balancing",
}


def load_and_validate_items(path: Path) -> List[Dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(f"Items JSON file not found: {path}")

    with open(path, "r", encoding="utf-8") as f:
        items = json.load(f)

    if not isinstance(items, list):
        raise ValueError("items.json must contain a JSON array of item objects.")

    seen_ids: set[int] = set()
    seen_codes: set[str] = set()
    seen_names: set[str] = set()

    for idx, item in enumerate(items):
        for field in ("id", "code_name", "name", "classification", "quantity", "category"):
            if field not in item:
                raise ValueError(f"Item #{idx} missing required field '{field}': {item}")

        item_id = item["id"]
        code = item["code_name"]
        name = item["name"]
        classification = item["classification"]

        if not isinstance(item_id, int):
            raise ValueError(f"Item '{code}' ID must be an integer, got: {type(item_id)}")
        if not IDENTIFIER_REGEX.match(code):
            raise ValueError(f"Item '{code}' has invalid C++/Python identifier code_name.")
        if classification not in CLASSIFICATION_MAP:
            raise ValueError(
                f"Item '{code}' has unknown classification '{classification}'. "
                f"Valid options: {list(CLASSIFICATION_MAP.keys())}"
            )

        if item_id in seen_ids:
            raise ValueError(f"Duplicate item ID {item_id} found on item '{code}'.")
        if code in seen_codes:
            raise ValueError(f"Duplicate item code_name '{code}'.")
        if name in seen_names:
            raise ValueError(f"Duplicate item display name '{name}'.")

        seen_ids.add(item_id)
        seen_codes.add(code)
        seen_names.add(name)

    return items


def load_and_validate_locations(path: Path) -> List[Dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(f"Locations JSON file not found: {path}")

    with open(path, "r", encoding="utf-8") as f:
        locations = json.load(f)

    if not isinstance(locations, list):
        raise ValueError("locations.json must contain a JSON array of location objects.")

    seen_ids: set[int] = set()
    seen_codes: set[str] = set()
    seen_names: set[str] = set()

    for idx, loc in enumerate(locations, start=1):
        for field in ("code_name", "name", "region"):
            if field not in loc:
                raise ValueError(f"Location #{idx} missing required field '{field}': {loc}")

        # ID can either be explicitly provided or inferred from the 1-based order in locations.json
        loc_id = loc.get("id", idx)
        loc["id"] = loc_id
        code = loc["code_name"]
        name = loc["name"]

        if not isinstance(loc_id, int):
            raise ValueError(f"Location '{code}' ID must be an integer, got: {type(loc_id)}")
        if not IDENTIFIER_REGEX.match(code):
            raise ValueError(f"Location '{code}' has invalid C++/Python identifier code_name.")

        if loc_id in seen_ids:
            raise ValueError(f"Duplicate location ID {loc_id} found on location '{code}'.")
        if code in seen_codes:
            raise ValueError(f"Duplicate location code_name '{code}'.")
        if name in seen_names:
            raise ValueError(f"Duplicate location display name '{name}'.")

        seen_ids.add(loc_id)
        seen_codes.add(code)
        seen_names.add(name)

    return locations


def generate_cpp_header(items: List[Dict[str, Any]], locations: List[Dict[str, Any]]) -> str:
    lines: List[str] = [
        "#ifndef __APDEFINITIONS_H__",
        "#define __APDEFINITIONS_H__",
        "",
        "// ===========================================================================",
        "// THIS FILE IS AUTO-GENERATED BY world/insaniquarium/generate_data.py.",
        "// DO NOT EDIT MANUALLY. Modify items.json and locations.json instead.",
        "// ===========================================================================",
        "",
        "#include <cstdint>",
        "",
        "namespace Sexy",
        "{",
        "\t// Archipelago Items",
        "\tenum class APItem : int64_t",
        "\t{",
        "\t\tNONE = 0LL,",
    ]

    for item in items:
        lines.append(f"\t\t{item['code_name']} = {item['id']}LL, // {item['name']}")

    lines.extend([
        "\t};",
        "",
        "\t// Archipelago Locations",
        "\tenum class APLocation : int64_t",
        "\t{",
        "\t\tNONE = 0LL,",
    ])

    for loc in locations:
        lines.append(f"\t\t{loc['code_name']} = {loc['id']}LL, // {loc['name']}")

    lines.extend([
        "\t};",
        "",
        "\t// -----------------------------------------------------------------------",
        "\t// Legacy / Convenience Constants for Direct Integer Access",
        "\t// -----------------------------------------------------------------------",
    ])

    for item in items:
        lines.append(f"\tstatic const int64_t AP_ITEM_{item['code_name']} = {item['id']}LL;")
    lines.append("")
    for loc in locations:
        lines.append(f"\tstatic const int64_t AP_LOCATION_{loc['code_name']} = {loc['id']}LL;")

    lines.extend([
        "",
        "\t// -----------------------------------------------------------------------",
        "\t// Helper String Conversion Functions",
        "\t// -----------------------------------------------------------------------",
        "\tinline const char* APItemToString(APItem theItem)",
        "\t{",
        "\t\tswitch (theItem)",
        "\t\t{",
    ])

    for item in items:
        lines.append(f'\t\tcase APItem::{item["code_name"]}: return "{item["name"]}";')

    lines.extend([
        '\t\tdefault: return "Unknown Item";',
        "\t\t}",
        "\t}",
        "",
        "\tinline const char* APItemName(int64_t theItemId)",
        "\t{",
        "\t\treturn APItemToString(static_cast<APItem>(theItemId));",
        "\t}",
        "",
        "\tinline const char* APLocationToString(APLocation theLocation)",
        "\t{",
        "\t\tswitch (theLocation)",
        "\t\t{",
    ])

    for loc in locations:
        lines.append(f'\t\tcase APLocation::{loc["code_name"]}: return "{loc["name"]}";')

    lines.extend([
        '\t\tdefault: return "Unknown Location";',
        "\t\t}",
        "\t}",
        "",
        "\tinline const char* APLocationName(int64_t theLocationId)",
        "\t{",
        "\t\treturn APLocationToString(static_cast<APLocation>(theLocationId));",
        "\t}",
        "}",
        "",
        "#endif // __APDEFINITIONS_H__",
        "",
    ])

    return "\n".join(lines)


def generate_python_items_data(items: List[Dict[str, Any]]) -> str:
    lines: List[str] = [
        "# ===========================================================================",
        "# THIS FILE IS AUTO-GENERATED BY world/insaniquarium/generate_data.py.",
        "# DO NOT EDIT MANUALLY. Modify items.json instead.",
        "# ===========================================================================",
        "",
        "from __future__ import annotations",
        "",
        "import enum",
        "from typing import TYPE_CHECKING, NamedTuple",
        "",
        "from BaseClasses import Item, ItemClassification as IC",
        "",
        'GAME_NAME = "Insaniquarium Deluxe"',
        "",
        "if TYPE_CHECKING:",
        "    from .. import InsaniquariumWorld",
        "",
        "",
        "class InsaniquariumItem(Item):",
        "    game = GAME_NAME",
        "",
        "",
        "class InsaniquariumItemData(NamedTuple):",
        "    classification: IC",
        "    quantity: int",
        "    id: int",
        "    category: str",
        "",
        "",
        "class APItem(enum.IntEnum):",
    ]

    for item in items:
        lines.append(f"    {item['code_name']} = {item['id']}")

    lines.extend([
        "",
        "",
        "# Item name constants for convenience and autocomplete",
    ])
    for item in items:
        lines.append(f'{item["code_name"]} = "{item["name"]}"')

    lines.extend([
        "",
        "",
        "ITEM_DATA: dict[str, InsaniquariumItemData] = {",
    ])

    for item in items:
        ic_str = CLASSIFICATION_MAP[item["classification"]]
        lines.append(
            f'    "{item["name"]}": InsaniquariumItemData('
            f'{ic_str}, {item["quantity"]}, {item["id"]}, "{item["category"]}"),'
        )

    lines.extend([
        "}",
        "",
        "ITEM_NAME_TO_ID: dict[str, int] = {name: data.id for name, data in ITEM_DATA.items()}",
        "",
        "ITEM_NAME_GROUPS: dict[str, set[str]] = {}",
        "for _name, _data in ITEM_DATA.items():",
        "    ITEM_NAME_GROUPS.setdefault(_data.category, set()).add(_name)",
        "",
        "item_table: dict[str, InsaniquariumItemData] = ITEM_DATA",
        "item_name_to_id: dict[str, int] = ITEM_NAME_TO_ID",
        "item_name_groups: dict[str, set[str]] = ITEM_NAME_GROUPS",
        "",
        "",
    ])

    return "\n".join(lines)


def generate_python_locations_data(locations: List[Dict[str, Any]]) -> str:
    lines: List[str] = [
        "# ===========================================================================",
        "# THIS FILE IS AUTO-GENERATED BY world/insaniquarium/generate_data.py.",
        "# DO NOT EDIT MANUALLY. Modify locations.json instead.",
        "# ===========================================================================",
        "",
        "from __future__ import annotations",
        "",
        "import enum",
        "",
        "from BaseClasses import Location",
        "",
        'GAME_NAME = "Insaniquarium Deluxe"',
        "",
        "class InsaniquariumLocation(Location):",
        "    game = GAME_NAME",
        "",
        "",
        "class InsaniquariumLocationData(enum.IntEnum):",
        '    """Every location with an ID. Auto-generated from locations.json."""',
        "",
        "    def __new__(cls, id: int, location_name: str, region: str = \"\") -> InsaniquariumLocationData:",
        "        obj = int.__new__(cls, id)",
        "        obj._value_ = id",
        "        return obj",
        "",
        "    def __init__(self, id: int, location_name: str, region: str = \"\") -> None:",
        "        self.id = id",
        "        self.location_name = location_name",
        "        self.region = region",
        "",
        "    @property",
        "    def category(self) -> str:",
        "        return self.region",
        "",
    ]

    for loc in locations:
        lines.append(f'    {loc["code_name"]} = {loc["id"]}, "{loc["name"]}", "{loc["region"]}"')

    lines.extend([
        "",
        "",
        "# Location name constants for convenience and autocomplete",
    ])
    for loc in locations:
        lines.append(f'{loc["code_name"]} = "{loc["name"]}"')

    lines.extend([
        "",
        "",
        "LOCATION_NAME_TO_ID: dict[str, int] = {",
        "    loc.location_name: loc.id for loc in InsaniquariumLocationData",
        "}",
        "",
        "LOCATION_NAME_GROUPS: dict[str, set[str]] = {}",
        "for _loc in InsaniquariumLocationData:",
        "    if _loc.region:",
        "        LOCATION_NAME_GROUPS.setdefault(_loc.region, set()).add(_loc.location_name)",
        "",
        "# Event location holding the Victory item; has no id.",
        'VICTORY_LOCATION_NAME = "Victory"',
        "",
        "location_name_to_id: dict[str, int] = LOCATION_NAME_TO_ID",
        "location_name_groups: dict[str, set[str]] = LOCATION_NAME_GROUPS",
        "",
    ])

    return "\n".join(lines)


def sync_file(target: Path, content: str, check_only: bool) -> bool:
    """Returns True if up-to-date, False if modified or needs change."""
    if target.is_file():
        existing = target.read_text(encoding="utf-8")
        if existing == content:
            return True

    if check_only:
        print(f"[OUT OF SYNC] {target}")
        return False

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"[WROTE] {target}")
    return True


def main() -> int:
    script_dir = Path(__file__).resolve().parent
    repo_root = script_dir.parent.parent

    parser = argparse.ArgumentParser(description="Generate C++ and Python enums from JSON definitions.")
    parser.add_argument("--items-json", type=Path, default=script_dir / "items.json")
    parser.add_argument("--locations-json", type=Path, default=script_dir / "locations.json")
    parser.add_argument("--cpp-header", type=Path, default=script_dir / "APDefinitions.h")
    parser.add_argument("--py-items", type=Path, default=script_dir / "item_data.py")
    parser.add_argument("--py-locations", type=Path, default=script_dir / "location_data.py")
    parser.add_argument("--check", action="store_true", help="Check that files are up to date without writing")

    args = parser.parse_args()

    items = load_and_validate_items(args.items_json)
    locations = load_and_validate_locations(args.locations_json)

    cpp_content = generate_cpp_header(items, locations)
    py_items_content = generate_python_items_data(items)
    py_locations_content = generate_python_locations_data(locations)

    all_synced = True
    all_synced &= sync_file(args.cpp_header, cpp_content, args.check)
    all_synced &= sync_file(args.py_items, py_items_content, args.check)
    all_synced &= sync_file(args.py_locations, py_locations_content, args.check)

    if args.check:
        if all_synced:
            print("All generated C++ and Python definitions are in sync with JSON definitions.")
            return 0
        else:
            print("Error: generated definitions are out of sync! Run generate_data.py to refresh.")
            return 1

    print(f"Successfully synchronized {len(items)} items and {len(locations)} locations.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

